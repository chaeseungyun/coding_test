# D03 | 1주차 구현 · 문자열
# 접근: 각 자리수마다 정렬할 수 있는 배열로 바꾸고 내림차순 정렬 -> 숫자로 변환 후 반환한다.
# 시간복잡도: O(n log n) 파이썬 정렬 시간 복잡도
# 막힌 지점: (없으면 "없음")
#
# ------------------------------------------------------------
# 문제: 정수 내림차순으로 배치하기
#
# 자연수 n이 주어진다.
# n의 각 자릿수를 큰 수부터 작은 수 순으로 다시 배치한 정수를 반환하라.
#
# 제한
# - n은 1 이상 8_000_000_000 이하인 자연수
#
# 입출력 예
#   118372  -> 873211    (자릿수 1,1,8,3,7,2를 내림차순으로 배치)
#   1        -> 1         (한 자리)
#   10203    -> 32100     (0은 뒤로 밀린다)
# ------------------------------------------------------------

def solution(n: int) -> int:
    return int("".join(sorted([s for s in str(n)], reverse=True)))


if __name__ == "__main__":
    tests = [
        (118372, 873211),
        (1, 1),
        (10203, 32100),
        (10, 10),
        (21, 21),
        (12, 21),
        (111, 111),
        (8000000000, 8000000000),
    ]

    for n, expected in tests:
        got = solution(n)
        ok = "OK" if got == expected else "FAIL"
        print(f"[{ok}] solution({n!r}) = {got!r} (expected {expected!r})")
