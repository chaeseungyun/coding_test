# D39 | 6주차 DFS · BFS
# 접근: bfs로 최단 거리를 구한다.
# 시간복잡도: O(n * m)
# 막힌 지점: (없으면 "없음") board[ny][nx] == '1' 을 board[ny][nx] == 1 로 잘못 써서 오답이 났었다.
# 20분 소요
# ------------------------------------------------------------
# 문제: 미로 탐색
#
# N행 M열 미로가 주어진다.
# 각 칸은 문자 '1' 또는 '0'이다.
# '1'은 이동할 수 있는 칸이고, '0'은 벽이라 이동할 수 없다.
#
# 왼쪽 위 칸에서 출발해 오른쪽 아래 칸까지 이동할 때,
# 지나야 하는 칸 수의 최솟값을 반환하라.
# 출발 칸과 도착 칸도 칸 수에 포함한다.
#
# 한 번에 상·하·좌·우로 인접한 칸만 이동할 수 있다.
# 미로 밖으로는 나갈 수 없다.
# 도착 칸까지 항상 갈 수 있는 미로만 주어진다.
#
# 미로는 문자열의 리스트 board로 주어진다.
# board의 길이가 N이고, 각 문자열의 길이가 M이다.
# board[r][c]가 r행 c열의 칸이다. 행·열은 0부터 센다.
# 출발은 board[0][0], 도착은 board[N - 1][M - 1]이다.
#
# 제한
# - 2 <= N, M <= 100
# - board[i]는 길이 M인 문자열이며 '0'과 '1'만 포함한다
# - board[0][0]과 board[N - 1][M - 1]은 항상 '1'
#
# 입출력 예
#   ["101111", "101010", "101011", "111011"]  -> 15
#       (벽을 돌아 왼쪽 위에서 오른쪽 아래까지 15칸)
#   ["110110", "110110", "111111", "111101"]  -> 9
#       (가운데 가로 통로를 지나 도착까지 9칸)
#   ["11", "11"]  -> 3
#       (2×2, 오른쪽 다음 아래. 시작·도착 포함 3칸)
#   ["11111", "00001"]  -> 6
#       (윗줄을 끝까지 간 뒤 한 칸 내려 도착)
#   ["110", "010", "011"]  -> 5
#       ((0,0)-(0,1)-(1,1)-(2,1)-(2,2))
#   7×7, 안쪽이 벽인 미로  -> 13
#       (왼쪽 줄을 내려간 뒤 맨 아래 줄을 가로지르면 13칸)
# ------------------------------------------------------------

from collections import deque

def solution(board: list[str]) -> int:
    direction = [(1, 0), (0, 1), (-1, 0), (0, -1)] # 하, 우, 상, 좌 
    # r, c
    n, m = len(board), len(board[0])
    # 방문한 노드는 다시 방문하지 않는다. 최소 거리를 구하기 때문.
    visited = [[0 for _ in range(m)] for _ in range(n)]

    queue = deque()
    start = (0, 0)
    end = (n - 1, m - 1)

    queue.append((start))
    visited[0][0] += 1

    # bfs 시작
    while queue:
        coord = queue.popleft()
        r, c = coord
        if (r, c) == end:
            return visited[r][c]
        for dr, dc in direction:
            nr, nc = r + dr, c + dc
            if n > nr >= 0 and m > nc >= 0 and board[nr][nc] == '1' and visited[nr][nc] == 0:
                queue.append((nr, nc))
                visited[nr][nc] = visited[r][c] + 1
    
    return 0


if __name__ == "__main__":
    tests = [
        (["101111", "101010", "101011", "111011"], 15),
        (["110110", "110110", "111111", "111101"], 9),
        (["11", "11"], 3),
        (["11111", "00001"], 6),
        (["110", "010", "011"], 5),
        (
            [
                "1011111",
                "1110001",
                "1000001",
                "1000001",
                "1000001",
                "1000001",
                "1111111",
            ],
            13,  # 왼쪽 줄 다음 맨 아래 줄
        ),
    ]

    for args, expected in tests:
        got = solution(*args) if isinstance(args, tuple) else solution(args)
        ok = "OK" if got == expected else "FAIL"
        print(f"[{ok}] solution({args!r}) = {got!r} (expected {expected!r})")
