# D08 | 2주차 해시
# 접근: 전체 폰켓몬 중 절반을 가져가는데 중복을 제외한 폰켓몬 종류 번호 수가 더 크면 종류 번호 수만큼, 반대면 N / 2 만큼 가져갈 수 있음.
# 시간복잡도: O(n)
# 막힌 지점: (없으면 "없음")
#
# ------------------------------------------------------------
# 문제: 폰켓몬
#
# 연구실에 N마리의 폰켓몬이 있다. N은 항상 짝수다.
# 각 폰켓몬은 종류 번호(정수)로만 구분한다. 같은 번호면 같은 종류다.
#
# 당신은 이 중에서 N/2마리를 가져갈 수 있다.
# 가능한 한 많은 종류를 포함하고 싶을 때, 가져갈 수 있는 종류의 최댓값을 반환하라.
#
# 제한
# - nums의 길이 N: 1 이상 10,000 이하 (항상 짝수)
# - nums의 원소: 1 이상 200,000 이하
#
# 입출력 예
#   [3, 1, 2, 3]          -> 2    (4마리 중 2마리. 종류는 1,2,3 세 가지지만 2마리만 고르므로 최대 2)
#   [3, 3, 3, 2, 2, 4]    -> 3    (6마리 중 3마리. 종류 3,2,4를 하나씩 고를 수 있음)
#   [3, 3, 3, 2, 2, 2]    -> 2    (종류가 2개뿐이라 3마리를 골라도 최대 2)
# ------------------------------------------------------------

def solution(nums: list[int]) -> int:
    # 종류 수
    k = len(set(nums))

    return min(len(nums) // 2, k)


if __name__ == "__main__":
    tests = [
        ([3, 1, 2, 3], 2),
        ([3, 3, 3, 2, 2, 4], 3),
        ([3, 3, 3, 2, 2, 2], 2),
        ([1, 1], 1),                    # 전부 같은 종류
        ([1, 2], 1),                    # 전부 다른 종류, N/2 = 1
        ([1, 2, 3, 4], 2),              # 종류가 N/2보다 많음
        ([1, 1, 1, 1], 1),              # 종류 1개, N/2 = 2
        ([1, 2, 3, 4, 5, 6], 3),        # 전부 다름, N/2 = 3
        ([7, 7, 7, 7, 7, 7, 7, 8], 2),  # 한 종류가 대부분
    ]

    for args, expected in tests:
        got = solution(*args) if isinstance(args, tuple) else solution(args)
        ok = "OK" if got == expected else "FAIL"
        print(f"[{ok}] solution({args!r}) = {got!r} (expected {expected!r})")
